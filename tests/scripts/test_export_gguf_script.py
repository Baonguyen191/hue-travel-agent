    """Gắn module `gguf` giả. Trả về dict: đường dẫn -> general.architecture (None = thiếu)."""
    architectures: dict[str, str | None] = {}

    class _Field:
        def __init__(self, parts: list[object]) -> None:
            self.parts = parts

    class _Reader:
        def __init__(self, path: str) -> None:
            name = architectures.get(path)
            self.fields: dict[str, _Field] = (
                {} if name is None else {"general.architecture": _Field([0, name.encode()])}
            )

    module = types.ModuleType("gguf")
    module.GGUFReader = _Reader  # type: ignore[attr-defined]
    monkeypatch.setitem(sys.modules, "gguf", module)
    return architectures


