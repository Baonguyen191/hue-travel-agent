# --- main --------------------------------------------------------------------


@dataclass
class Pipeline:
    config: SftConfig
    calls: list[list[str]] = field(default_factory=list)
    merged_from: list[Path] = field(default_factory=list)

    @property
    def run_dir(self) -> Path:
        return self.config.sft.run_dir

    @property
    def artifacts(self) -> Path:
        return repo_artifacts_dir(self.config.sft.run_name)


@pytest.fixture
def pipeline(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Iterator[Pipeline]:
    monkeypatch.chdir(tmp_path)
    config = make_config(tmp_path, checkpoint=500)
    state = Pipeline(config=config)
    monkeypatch.setattr(export_gguf, "load_sft_config", lambda path: config)

    adapters = repo_artifacts_dir(config.sft.run_name) / "adapters"
    for step in (250, 500):
        step_dir = adapters / f"step-{step}"
        step_dir.mkdir(parents=True)
        (step_dir / "adapter_model.safetensors").write_bytes(f"adapter {step}".encode())

    snapshot = tmp_path / "snapshot"
    snapshot.mkdir()
    monkeypatch.setattr(export_gguf, "hf_snapshot_dir", lambda repo, revision: snapshot)

    def fake_merge(snapshot_dir: Path, adapter: Path, out: Path) -> None:
        state.merged_from.append(adapter)
        out.mkdir(parents=True)

    def fake_run(command: list[str]) -> str:
        state.calls.append(command)
        if command[0] == "git":
            return "abc123\n"
        if command[:2] == ["ollama", "show"]:
            return TEMPLATE
        if command[0] == "ollama":
            return ""
        if command[1].endswith("convert_hf_to_gguf.py"):
            Path(command[command.index("--outfile") + 1]).write_bytes(b"bf16 weights")
            return ""
        if command[0].endswith("llama-quantize.exe"):
            Path(command[2]).write_bytes(b"q4 weights")
            return ""
        raise AssertionError(f"lệnh không ngờ tới: {command}")

    monkeypatch.setattr(export_gguf, "merge", fake_merge)
    monkeypatch.setattr(export_gguf, "text_weights", lambda modelfile: BASE)
    monkeypatch.setattr(export_gguf, "run", fake_run)
    yield state


def _ollama_create_names(calls: list[list[str]]) -> list[str]:
    return [command[2] for command in calls if command[:2] == ["ollama", "create"]]


def test_record_uses_config_checkpoint_and_writes_export_json(pipeline: Pipeline) -> None:
    assert export_gguf.main(["--checkpoint", "250", "--record"]) == 0

    step_dir = pipeline.run_dir / "export" / "step-500"
    assert pipeline.merged_from == [pipeline.artifacts / "adapters" / "step-500"]
    assert not (step_dir / "model-bf16.gguf").exists()

    record = json.loads((pipeline.artifacts / "export.json").read_text(encoding="utf-8"))
    assert record["checkpoint"] == 500
    assert record["ollama_model"] == pipeline.config.export.ollama_model
    assert record["llama_cpp_commit"] == "abc123"

    final = step_dir / f"model-{pipeline.config.export.quantization}.gguf"
    modelfile = (step_dir / "Modelfile").read_text(encoding="utf-8")
    assert from_lines(modelfile) == [str(final), PROJECTOR]
    assert _ollama_create_names(pipeline.calls) == [pipeline.config.export.ollama_model]


def test_named_checkpoint_gets_step_suffix_and_no_export_json(pipeline: Pipeline) -> None:
    assert export_gguf.main(["--checkpoint", "250"]) == 0

    assert _ollama_create_names(pipeline.calls) == [
        f"{pipeline.config.export.ollama_model}-step-250"
    ]
    assert not (pipeline.artifacts / "export.json").exists()


def test_record_without_config_checkpoint_stops_before_any_work(
    pipeline: Pipeline, monkeypatch: pytest.MonkeyPatch
) -> None:
    config = pipeline.config
    no_checkpoint = config.model_copy(
        update={"export": config.export.model_copy(update={"checkpoint": None})}
    )
    monkeypatch.setattr(export_gguf, "load_sft_config", lambda path: no_checkpoint)

    with pytest.raises(SystemExit, match="export.checkpoint"):
        export_gguf.main(["--record"])

    assert pipeline.merged_from == []
    assert pipeline.calls == []
    assert not (pipeline.artifacts / "export.json").exists()


def test_skip_ollama_runs_no_ollama_command(
    pipeline: Pipeline, capsys: pytest.CaptureFixture[str]
) -> None:
    assert export_gguf.main(["--checkpoint", "250", "--skip-ollama"]) == 0

    assert not any(command[0] == "ollama" for command in pipeline.calls)
    printed = json.loads(capsys.readouterr().out)
    assert printed["checkpoint"] == 250
    assert "ollama_model" not in printed


def test_merged_dir_is_removed_after_convert_and_gguf_kept(pipeline: Pipeline) -> None:
    assert export_gguf.main(["--checkpoint", "250"]) == 0

    step_dir = pipeline.run_dir / "export" / "step-250"
    assert not (step_dir / "merged").exists()
    assert (step_dir / f"model-{pipeline.config.export.quantization}.gguf").exists()


def test_convert_failure_keeps_merged_dir_for_debugging(
    pipeline: Pipeline, monkeypatch: pytest.MonkeyPatch
) -> None:
    fake_run = export_gguf.run

    def failing_convert(command: list[str]) -> str:
        if command[1].endswith("convert_hf_to_gguf.py"):
            raise subprocess.CalledProcessError(1, command)
        return fake_run(command)

    monkeypatch.setattr(export_gguf, "run", failing_convert)

    with pytest.raises(subprocess.CalledProcessError):
        export_gguf.main(["--checkpoint", "250"])

    assert (pipeline.run_dir / "export" / "step-250" / "merged").exists()


def test_stale_merged_dir_is_cleared_before_merge(
    pipeline: Pipeline, monkeypatch: pytest.MonkeyPatch
) -> None:
    stale = pipeline.run_dir / "export" / "step-250" / "merged"
    stale.mkdir(parents=True)
    (stale / "old-shard.safetensors").write_bytes(b"old")
    seen_at_merge: list[bool] = []
    fake_merge = export_gguf.merge

    def spy_merge(snapshot_dir: Path, adapter: Path, out: Path) -> None:
        seen_at_merge.append((out / "old-shard.safetensors").exists())
        fake_merge(snapshot_dir, adapter, out)

    monkeypatch.setattr(export_gguf, "merge", spy_merge)

    assert export_gguf.main(["--checkpoint", "250"]) == 0

    assert seen_at_merge == [False]
    assert not (stale / "old-shard.safetensors").exists()


# --- --smoke -----------------------------------------------------------------


def _make_smoke_adapter(pipeline: Pipeline) -> Path:
    smoke = pipeline.run_dir / "smoke" / "final"
    smoke.mkdir(parents=True)
    (smoke / "adapter_model.safetensors").write_bytes(b"smoke adapter")
    return smoke


def test_smoke_exports_from_smoke_adapter(
    pipeline: Pipeline, capsys: pytest.CaptureFixture[str]
) -> None:
    smoke = _make_smoke_adapter(pipeline)

    assert export_gguf.main(["--smoke"]) == 0

    assert pipeline.merged_from == [smoke]
    work = pipeline.run_dir / "export" / "smoke"
    final = work / f"model-{pipeline.config.export.quantization}.gguf"
    assert final.exists()
    assert _ollama_create_names(pipeline.calls) == [f"{pipeline.config.export.ollama_model}-smoke"]
    printed = json.loads(capsys.readouterr().out)
    assert printed["checkpoint"] == "smoke"
    assert not (pipeline.artifacts / "export.json").exists()


def test_smoke_without_adapter_stops_before_any_work(pipeline: Pipeline) -> None:
    with pytest.raises(SystemExit, match="--smoke"):
        export_gguf.main(["--smoke"])

    assert pipeline.merged_from == []
    assert pipeline.calls == []


@pytest.mark.parametrize("extra", [["--record"], ["--checkpoint", "250"]])
def test_smoke_conflicts_stop_before_any_work(pipeline: Pipeline, extra: list[str]) -> None:
    _make_smoke_adapter(pipeline)

    with pytest.raises(SystemExit, match="--smoke"):
        export_gguf.main(["--smoke", *extra])

    assert pipeline.merged_from == []
    assert pipeline.calls == []
    assert not (pipeline.artifacts / "export.json").exists()
