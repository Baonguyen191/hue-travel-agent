REPO = Path(__file__).parents[2]
SFT_YAML = REPO / "configs" / "sft.yaml"
BASE = r"C:\Users\u\.ollama\models\blobs\sha256-aaaa"
PROJECTOR = r"C:\Users\u\.ollama\models\blobs\sha256-bbbb"
TEMPLATE = (
    '# Modelfile generated by "ollama show"\n'
    f"FROM {BASE}\n"
    f"FROM {PROJECTOR}\n"
    "RENDERER qwen3.5\n"
    "PARAMETER temperature 1\n"
)


def make_config(tmp_path: Path, checkpoint: int | None) -> SftConfig:
    """Config từ configs/sft.yaml, output nặng chuyển vào tmp_path."""
    config = load_sft_config(SFT_YAML)
    sft = config.sft.model_copy(update={"runs_dir": tmp_path / "runs"})
    export = config.export.model_copy(update={"checkpoint": checkpoint})
    return config.model_copy(update={"sft": sft, "export": export})


